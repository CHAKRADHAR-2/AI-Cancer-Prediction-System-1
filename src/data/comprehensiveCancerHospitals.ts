// Function to get cancer hospitals by state
export const getCancerHospitalsByState = (state: string): CancerHospitalData[] => {
  // Filter hospitals by state and ensure they are cancer-related
  const stateHospitals = comprehensiveCancerHospitals.filter(hospital => 
    hospital.state === state && (
      hospital.name.toLowerCase().includes('cancer') ||
      hospital.name.toLowerCase().includes('oncology') ||
      hospital.specializations.some(spec => 
        spec.toLowerCase().includes('oncology') || 
        spec.toLowerCase().includes('cancer')
      )
    )
  );
  
  // If no hospitals found in the exact state, try fuzzy matching for similar state names
  if (stateHospitals.length === 0) {
    const fuzzyMatches = comprehensiveCancerHospitals.filter(hospital => 
      hospital.state.toLowerCase().includes(state.toLowerCase()) ||
      state.toLowerCase().includes(hospital.state.toLowerCase())
    );
    return fuzzyMatches;
  }
  
  return stateHospitals;
};

// Function to get all cancer hospitals
export const getAllCancerHospitals = (): CancerHospitalData[] => {
  return comprehensiveCancerHospitals;
};

// Function to search cancer hospitals by name or specialization
export const searchCancerHospitals = (query: string): CancerHospitalData[] => {
  const searchTerm = query.toLowerCase();
  return comprehensiveCancerHospitals.filter(hospital =>
    hospital.name.toLowerCase().includes(searchTerm) ||
    hospital.city.toLowerCase().includes(searchTerm) ||
    hospital.state.toLowerCase().includes(searchTerm) ||
    hospital.specializations.some(spec => spec.toLowerCase().includes(searchTerm))
  );
};